#!/usr/bin/env node
// Generates docs/guide/signals.md, the guide's table of every sloppyCAN signal the car, the truck
// and the tractor carry, from contract/carlito_contract.json. Run after editing the contract or a
// guide page's sloppyCAN table:
//     node tools/gen_guide_signals.mjs
//     node tools/gen_guide_signals.mjs --check   # the gates' form: exit 1 when the page is stale
// "What it is" is the contract desc's first sentence, parentheses removed. "More" links the first
// topic page (pages.json order) whose "What you see in sloppyCAN" table names the signal, else
// the vehicle family page whose table does.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const guide = resolve(root, 'docs/guide');
const outPath = resolve(guide, 'signals.md');
const LAND = ['car', 'truck', 'tractor'];
// Pages that are not topic pages: a family page is only the fallback "More" link.
const NOT_TOPICS = ['car.md', 'truck.md', 'tractor.md', 'template.md', 'signals.md'];

const contract = JSON.parse(readFileSync(resolve(root, 'contract/carlito_contract.json'), 'utf8'));
const allPages = JSON.parse(readFileSync(resolve(guide, 'pages.json'), 'utf8')).pages.filter((p) => !p.hidden);
const FAMILY_PAGES = ['car.md', 'truck.md', 'tractor.md'];

// Signal name -> the first topic page whose sloppyCAN table row names it, else the family page's.
const home = {};
for (const p of [...allPages.filter((q) => !NOT_TOPICS.includes(q.file)),
  ...allPages.filter((q) => FAMILY_PAGES.includes(q.file))]) {
  const text = readFileSync(resolve(guide, p.file), 'utf8').replace(/\r\n/g, '\n');
  const section = text.split(/^## What you see in sloppyCAN$/m)[1];
  if (!section) continue;
  for (const row of section.split(/^## /m)[0].split('\n').filter((l) => l.startsWith('| `'))) {
    for (const m of row.split('|')[1].matchAll(/`([A-Za-z_]+)`/g)) home[m[1]] ??= p;
  }
}

function firstSentence(desc) {
  let s = (desc.match(/^(.*?[.!?])(\s|$)/) || [null, desc])[1];
  for (let prev = ''; prev !== s;) { prev = s; s = s.replace(/\s*\([^()]*\)/g, ''); }
  return s.replace(/\|/g, '\\|');
}

const rows = contract.signals.filter((s) => s.vehicles.some((v) => LAND.includes(v))).map((s) => {
  const p = home[s.name];
  return `| \`${s.name}\` | ${s.dir} | ${s.unit} | ${LAND.filter((v) => s.vehicles.includes(v)).join(', ')} | ` +
    `${firstSentence(s.desc || '')} | ${p ? `[${p.title}](${p.file})` : ''} |`;
});

const out = `# All sloppyCAN signals

<p class="lead">Every signal the car, the truck and the tractor exchange with sloppyCAN. In: sent by
sloppyCAN to the simulator. Out: sent by the simulator.</p>

<!-- Generated by tools/gen_guide_signals.mjs from contract/carlito_contract.json (version ${contract.version}): edit the contract, then rerun it. -->

| Signal | Direction | Unit | Vehicles | What it is | More |
| --- | --- | --- | --- | --- | --- |
${rows.join('\n')}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing = stale */ }
  if (current !== out) {
    console.log('docs/guide/signals.md is stale: run node tools/gen_guide_signals.mjs');
    process.exit(1);
  }
  console.log('docs/guide/signals.md is current.');
} else {
  writeFileSync(outPath, out);
  console.log(`Wrote docs/guide/signals.md: ${rows.length} signals.`);
}
